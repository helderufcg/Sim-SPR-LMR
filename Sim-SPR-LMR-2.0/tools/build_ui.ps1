param(
    [switch]$Apply,
    [string]$OutputRoot
)

$ErrorActionPreference = "Stop"

$repoRoot = Split-Path -Parent $PSScriptRoot
$appRoot = Join-Path $repoRoot "sim-spr-lmr-simulator"
$uiRoot = Join-Path $repoRoot "ui"
$defaultOutputRoot = Join-Path $repoRoot ".tmp\generated-ui"

if (-not $OutputRoot) {
    $OutputRoot = if ($Apply) { $appRoot } else { $defaultOutputRoot }
}

New-Item -ItemType Directory -Force -Path $OutputRoot | Out-Null

$files = @(
    # The main runtime UI is intentionally excluded. Sim_LMR_interface.py
    # contains manual/stable visual edits not represented by a current .ui
    # source. Keep ui/main_interface_stable_legacy.ui as historical reference
    # only until a faithful Qt Designer source is reconstructed.
    @{ Input = "Instructions.ui"; Output = "instructions.py" },
    @{ Input = "open_extern_file.ui"; Output = "open_extern_file.py" },
    @{ Input = "save_files.ui"; Output = "save_files.py" },
    @{ Input = "save_table.ui"; Output = "save_table.py" }
)

function Invoke-Pyuic5 {
    param(
        [Parameter(Mandatory = $true)][string]$InputFile,
        [Parameter(Mandatory = $true)][string]$OutputFile
    )

    if (Get-Command pyuic5 -ErrorAction SilentlyContinue) {
        & pyuic5 --resource-suffix= $InputFile -o $OutputFile
    }
    else {
        & python -m PyQt5.uic.pyuic --resource-suffix= $InputFile -o $OutputFile
    }
}

foreach ($file in $files) {
    $inputFile = Join-Path $uiRoot $file.Input
    $outputFile = Join-Path $OutputRoot $file.Output
    Invoke-Pyuic5 -InputFile $inputFile -OutputFile $outputFile
    Write-Host "Generated $outputFile"
}

if (-not $Apply) {
    Write-Host ""
    Write-Host "Generated UI modules were written to $OutputRoot."
    Write-Host "The main runtime UI is not generated by this script."
    Write-Host "The runtime modules were not overwritten. Use -Apply only for extracted secondary dialogs."
}
